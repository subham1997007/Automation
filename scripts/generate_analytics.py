def _sibling_row(s: dict[str, Any], is_current: bool = False, jira_url: str = "") -> str:
    key      = s.get("key") or "?"
    summary  = s.get("summary") or "—"
    status   = s.get("status") or "To Do"
    assignee = s.get("assignee") or ""
    updated  = _parse_date(s.get("updated") or "")
    icon, color = _status_icon(status)
    url = jira_url or _jira_url(key)

    # Clean up "unassigned" → "—"
    if not assignee or assignee.lower() in ("unassigned", "none", "null", ""):
        assignee = "—"

    # Detect cross-project stories using Jira prefix, not repo name
    # e.g. BDRSP-* is main project, BDATART-* is cross-project
    jira_prefix = os.getenv("JIRA_PROJECT_KEY", "").upper()
    if not jira_prefix:
        # Auto-detect: find most common prefix in .memory/devflow/stories/
        try:
            import glob as _glob
            _keys = [Path(p).stem.split("-")[0].upper()
                     for p in _glob.glob(str(AUTO_DIR / ".memory" / "devflow" / "stories" / "*.json"))]
            from collections import Counter as _Counter
            if _keys:
                jira_prefix = _Counter(_keys).most_common(1)[0][0]
        except Exception:
            pass
    key_prefix = key.split("-")[0].upper()
    is_cross_project = bool(jira_prefix) and key_prefix != jira_prefix

    # Cross-project stories get muted styling
    if is_cross_project and not is_current:
        opacity = "opacity:.55;"
        proj_pill = (f'<span style="background:#21262d;color:#8b949e;border:1px solid #30363d;'
                     f'padding:1px 6px;border-radius:8px;font-size:.7rem;">{key_prefix}</span>')
    else:
        opacity = ""
        proj_pill = ""

    # Highlight = In Progress in Jira (blue left border), NOT DevFlow badge
    is_in_progress = "in progress" in status.lower()
    highlight = f"border-left:3px solid #388bfd;" if is_in_progress else ""
    devflow_badge = ('<span style="background:#1a2a4a;color:#58a6ff;border:1px solid #1f6feb;'
                     'padding:1px 7px;border-radius:10px;font-size:.72rem;margin-left:6px;">DevFlow</span>'
                     if is_current else "")

    return f'''
    <div class="tree-sibling" style="{highlight}{opacity}">
      <span style="color:{color};margin-right:4px;">{icon}</span>
      {proj_pill}
      <a href="{url}" target="_blank" class="tree-key">{key}</a>
      {devflow_badge}
      <span class="tree-summary">{summary[:80]}{"…" if len(summary)>80 else ""}</span>
      <span class="tree-meta">{status} · {assignee} · {updated}</span>
    </div>'''


def _clean_assignee(val: str | None) -> str:
    """Return '—' for unassigned/null values, otherwise the name."""
    if not val or val.lower() in ("unassigned", "none", "null", ""):
        return "—"
    return val


def _current_user_display_name(pi: dict[str, Any]) -> str:
    """Derive the current developer's Jira display name.

    All stories in the pi-snapshot were fetched with assignee = JIRA_USERNAME,
    so the first non-empty assignee display name found IS the current user.
    Falls back to the JIRA_USERNAME env var (email) if the snapshot is empty.
    """
    for s in pi.get("unparented") or []:
        a = s.get("assignee") or ""
        if a and a.lower() not in ("unassigned", "none", "null", "—", ""):
            return a
    for feat in (pi.get("features") or {}).values():
        for s in feat.get("stories") or []:
            a = s.get("assignee") or ""
            if a and a.lower() not in ("unassigned", "none", "null", "—", ""):
                return a
    return os.getenv("JIRA_USERNAME", "")


def _is_my_story(sib: dict[str, Any], current_user: str, devflow_ids: set[str]) -> bool:
    """True if this story belongs to the current developer or is DevFlow-tracked."""
    if sib.get("key", "") in devflow_ids:
        return True
    if not current_user:
        return True   # no user info → show all
    assignee = (sib.get("assignee") or "").strip()
    return assignee.lower() == current_user.lower()


def _subtask_tree_nodes(subtasks: list[dict[str, Any]]) -> str:
    """Render subtasks as always-visible child tree nodes under a story."""
    if not subtasks:
        return ""
    rows = ""
    for i, sub in enumerate(subtasks):
        sub_status = sub.get("status") or "—"
        sub_icon, sub_color = _status_icon(sub_status)
        sub_key = sub.get("key") or "?"
        sub_summary = (sub.get("summary") or "—")[:110]
        connector = "└─" if i == len(subtasks) - 1 else "├─"
        rows += f'''
    <div class="subtask-tree-node">
      <span class="subtask-connector">{connector}</span>
      <span style="color:{sub_color};font-size:.85rem;">{sub_icon}</span>
      <a href="{_jira_url(sub_key)}" target="_blank" class="tree-key subtask-key"
         onclick="event.stopPropagation()">{sub_key}</a>
      <span class="subtask-summary">{sub_summary}</span>
      <span class="tree-meta">{sub_status}</span>
    </div>'''
    return rows


def _story_node(sib: dict[str, Any], *, df_story: dict[str, Any] | None = None) -> str:
    key = sib.get("key") or (df_story or {}).get("id") or "?"
    story_id = f"story_{_safe_dom_id(key)}"
    summary = sib.get("summary") or (df_story or {}).get("summary") or "—"
    status = sib.get("status") or (df_story or {}).get("jira_status") or "To Do"
    # Always override with "Cancelled" for stories in the cancelled list
    if key in CANCELLED_STORY_KEYS:
        status = "Cancelled"
    assignee = _clean_assignee(sib.get("assignee") or (df_story or {}).get("assignee"))
    updated = _parse_date(sib.get("updated") or (df_story or {}).get("updated") or "")
    icon, color = _status_icon(status)
    is_devflow = df_story is not None

    # Highlight only if story is genuinely "In Progress"
    is_in_progress = "in progress" in status.lower()
    highlight_style = "border-left:3px solid #388bfd;background:rgba(56,139,253,.06);" if is_in_progress else ""

    devflow_badge = '<span class="devflow-badge">DevFlow</span>' if is_devflow else ""

    # ── Subtasks: prefer pi-snapshot data, fall back to DevFlow story subtasks ─
    subtasks: list[dict[str, Any]] = (
        sib.get("subtasks")
        or (df_story or {}).get("subtasks")
        or []
    )
    subtask_nodes = _subtask_tree_nodes(subtasks)

    # ── DevFlow stage summary (only for DevFlow stories) ─────────────────────
    devflow_detail = ""
    if is_devflow and df_story:
        mr_url   = df_story.get("mr_url") or ""
        next_gate = df_story.get("next_gate") or ""
        ai_time  = df_story.get("ai_time") or "—"
        test_v   = df_story.get("test_verdict") or "—"
        test_color = "#3fb950" if test_v == "passed" else "#f85149" if test_v == "failed" else "#8b949e"
        mr_html = ""
        if mr_url:
            mr_html = f'<div class="detail-item" style="margin-left:22px;">🔗 <a href="{mr_url}" target="_blank" style="color:#58a6ff;">MR</a></div>'
        elif next_gate:
            mr_html = f'<div class="detail-item" style="margin-left:22px;">⏸ <span style="color:#d29922;font-size:.78rem;">{next_gate}</span></div>'
        devflow_detail = f'''
    <div style="display:flex;gap:14px;flex-wrap:wrap;padding:4px 4px 4px 22px;font-size:.78rem;color:#8b949e;">
      <span>🤖 AI: <b style="color:#a371f7;">{ai_time}</b></span>
      <span>🧪 Tests: <b style="color:{test_color};">{test_v}</b></span>
      {mr_html}
    </div>'''

    # ── Children content: subtasks + devflow summary ──────────────────────────
    has_children = bool(subtask_nodes or devflow_detail)
    toggle_icon  = "▶" if has_children else "▸"
    children_div = ""
    if has_children:
        children_div = f'''
      <div class="story-children" id="children_{story_id}" style="display:none">
        <div class="subtasks-container">{subtask_nodes}</div>
        {devflow_detail}
      </div>'''

    return f'''
    <div class="story-node" id="{story_id}" style="{highlight_style}">
      <div class="story-header" onclick="{'toggleTree(' + chr(39) + story_id + chr(39) + ')' if has_children else ''}">
        <span class="tree-toggle" id="toggle_{story_id}">{toggle_icon}</span>
        <span style="color:{color};margin-right:4px;">{icon}</span>
        <a href="{_jira_url(key)}" target="_blank" class="tree-key"
           onclick="event.stopPropagation()">{key}</a>
        {devflow_badge}
        <span class="tree-summary">{summary[:110]}{"…" if len(summary) > 110 else ""}</span>
        <span class="tree-meta">{status} · {assignee} · {updated}</span>
      </div>{children_div}
    </div>'''


