def _fmt_duration(seconds: float) -> str:
    if seconds <= 0:
        return "—"
    if seconds < 60:
        return f"{seconds:.0f}s"
    m, s = divmod(int(seconds), 60)
    if m < 60:
        return f"{m}m {s}s"
    h, m2 = divmod(m, 60)
    return f"{h}h {m2}m"


def _parse_date(s: str) -> str:
    """Return a short human date from ISO string."""
    if not s:
        return "—"
    try:
        dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
        return dt.strftime("%b %d, %Y")
    except Exception:
        return s[:10]


def _jira_url(story_id: str) -> str:
    base = os.getenv("JIRA_BASE_URL", "").rstrip("/")
    if base:
        return f"{base}/browse/{story_id}"
    return f"https://jira.atlassian.com/browse/{story_id}"


def _live_jira_enabled() -> bool:
    value = (os.getenv("AUTOMATION_ANALYTICS_LIVE_JIRA") or "1").strip().lower()
    return value not in {"0", "false", "no", "off", "disabled"}


def _bucket_feature_stories(stories: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    completed: list[dict[str, Any]] = []
    in_progress: list[dict[str, Any]] = []
    pending: list[dict[str, Any]] = []
    for story in stories:
        status_category = (story.get("status_category") or "").lower()
        status = (story.get("status") or "").lower()
        if status_category == "done" or status in {"done", "closed", "resolved"}:
            completed.append(story)
        elif status_category == "in progress":
            in_progress.append(story)
        else:
            pending.append(story)
    return completed, in_progress, pending


def _enrich_feature_context_from_jira(jira_client: Any, feature: dict[str, Any]) -> dict[str, Any]:
    """Load full sibling story details so the tree can show story subtasks."""
    if not feature.get("ok"):
        return feature

    enriched: list[dict[str, Any]] = []
    for item in feature.get("sibling_stories") or []:
        key = item.get("key")
        if not key:
            continue
        try:
            full = jira_client.read_issue(key)
            merged = {**item, **full}
            enriched.append(merged)
        except Exception:
            enriched.append(item)

    if not enriched:
        return feature

    completed, in_progress, pending = _bucket_feature_stories(enriched)
    feature = dict(feature)
    feature.update(
        {
            "sibling_stories": enriched,
            "completed_stories": completed,
            "in_progress_stories": in_progress,
            "pending_stories": pending,
            "completed_count": len(completed),
            "total_sibling_count": len(enriched),
        }
    )
    return feature


def _refresh_from_jira(jira_id: str) -> tuple[dict[str, Any], dict[str, Any], str]:
    """Read the latest story and Feature tree directly from Jira.

    The dashboard should reflect the Jira board each time it is generated. If
    Jira is unreachable, callers fall back to local memory and show the stale
    data instead of failing the whole report.
    """
    if not _live_jira_enabled():
        return {}, {}, "Live Jira refresh disabled by AUTOMATION_ANALYTICS_LIVE_JIRA."

    jira_src = AUTO_DIR / "mcp-servers" / "jira-mcp" / "src"
    if str(jira_src) not in sys.path:
        sys.path.insert(0, str(jira_src))
    try:
        import jira_client  # type: ignore

        story = jira_client.read_issue(jira_id)
        feature = jira_client.feature_context_for_story(story)
        feature = _enrich_feature_context_from_jira(jira_client, feature)
        return story, feature, ""
    except Exception as exc:
        return {}, {}, f"Live Jira refresh failed: {exc}"


def _safe_dom_id(value: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in value)


def _merge_unique_issues(existing: list[dict[str, Any]], incoming: list[dict[str, Any]]) -> list[dict[str, Any]]:
    merged: dict[str, dict[str, Any]] = {}
    for item in existing + incoming:
        key = item.get("key")
        if key:
            merged[key] = item
    return list(merged.values())


def _story_from_feature_context(jira_id: str, fc: dict[str, Any]) -> dict[str, Any]:
    for item in fc.get("sibling_stories") or []:
        if item.get("key") == jira_id:
            return item
    for bucket in ("completed_stories", "in_progress_stories", "pending_stories"):
        for item in fc.get(bucket) or []:
            if item.get("key") == jira_id:
                return item
    return {}


def _fallback_feature_context(raw: dict[str, Any], story: dict[str, Any]) -> dict[str, Any]:
    """Build the best tree context possible from locally stored data.

    DevFlow now stores the full story, but older memory files may only contain a
    failed feature lookup. This fallback lets the dashboard still show the
    parent Feature row when the story payload contains parent fields.
    """
    fc = raw.get("feature_context") or {}
    if fc.get("ok") or (fc.get("feature") or {}).get("key"):
        return fc

    parent_key = story.get("parent") or raw.get("feature_key") or ""
    if not parent_key:
        return fc

    parent_summary = story.get("parent_summary") or parent_key
    parent_status = story.get("parent_status") or ""
    status_category = story.get("status_category") or ""
    story_status = story.get("status") or "To Do"
    current = {
        "key": story.get("key") or raw.get("jira_id") or "",
        "summary": story.get("summary") or "",
        "status": story_status,
        "status_category": status_category,
        "issue_type": story.get("issue_type") or "Story",
        "assignee": story.get("assignee") or "—",
        "priority": story.get("priority") or "",
        "updated": story.get("updated") or "",
    }
    completed = [current] if status_category.lower() == "done" or story_status.lower() in {"done", "closed", "resolved"} else []
    in_progress = [current] if status_category.lower() == "in progress" else []
    pending = [] if completed or in_progress else [current]
    return {
        "ok": True,
        "story_key": current["key"],
        "feature": {
            "key": parent_key,
            "name": parent_summary,
            "issue_type": story.get("parent_issue_type") or "Feature",
            "status": parent_status,
            "description": "",
            "acceptance_criteria": [],
        },
        "feature_goal": parent_summary,
        "current_story_fit": f'{current["key"]} contributes to {parent_key} by delivering: {current["summary"]}.',
        "sibling_stories": [current],
        "completed_stories": completed,
        "in_progress_stories": in_progress,
        "pending_stories": pending,
        "completed_count": len(completed),
        "total_sibling_count": 1,
        "search_error": "Sibling list not available in old local memory; run DevFlow start again to refresh full Feature context.",
        "rule": "Feature context inferred from the stored story parent fields.",
    }


def load_story(path: Path) -> dict[str, Any] | None:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None

    jira_id    = raw.get("jira_id") or path.stem.upper()
    stage      = raw.get("stage") or "start"
    live_story, live_fc, live_error = _refresh_from_jira(jira_id)
    if live_story:
        raw.update(
            {
                "jira_id": jira_id,
                "story": live_story,
                "story_updated": live_story.get("updated"),
                "feature_context": live_fc,
                "feature_key": ((live_fc.get("feature") or {}).get("key") if live_fc else raw.get("feature_key")),
                "jira_refresh_updated_at_epoch": int(time.time()),
            }
        )
        try:
            path.write_text(json.dumps(raw, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
        except OSError:
            pass
    story_raw  = live_story or raw.get("story") or {}
    fc         = live_fc or _fallback_feature_context(raw, story_raw)
    live_status = "fresh" if live_story else ("disabled" if not _live_jira_enabled() else "fallback")
    feat       = fc.get("feature") or {}
    ca         = raw.get("codebase_analysis") or {}
    timings    = raw.get("stage_timings") or []
    updated    = story_raw.get("updated") or raw.get("story_updated") or raw.get("updated_at") or ""
    next_gate  = raw.get("next_gate") or ""
    mr_result  = raw.get("mr_result") or {}

    ai_s   = sum(t.get("elapsed_s", 0) for t in timings if t.get("actor") == "ai")
    hu_s   = sum(t.get("elapsed_s", 0) for t in timings if t.get("actor") == "human")
    approvals = sum(1 for t in timings if t.get("actor") == "human")

    # Try loading report JSON for richer data
    report: dict[str, Any] = {}
    report_path = REPORTS_DIR / jira_id / "automation-report.json"
    if report_path.exists():
        try:
            report = json.loads(report_path.read_text(encoding="utf-8"))
        except Exception:
            pass

    mr_url   = report.get("mr_url") or mr_result.get("web_url") or ""
    mr_title = report.get("mr_title") or ""
    files_changed = report.get("files_changed") or []
    test_ok  = (report.get("test_result") or {}).get("ok")

    # Derive status
    status_info = STATUS_FROM_STAGE.get(stage, ("In Progress", "#1f6feb", "#388bfd"))
    if stage == "create_mr" and mr_url:
        status_info = ("PR Created", "#238636", "#3fb950")

    progress_pct = int((STAGE_PROGRESS.get(stage, 0) / max(len(STAGE_ORDER) - 1, 1)) * 100)

    feature_key     = feat.get("key") or raw.get("feature_key") or ""
    feature_name    = feat.get("name") or feat.get("summary") or ""
    feature_status  = feat.get("status") or ""
    feature_desc    = (feat.get("description") or "")[:200]
    completed_siblings = fc.get("completed_count") or 0

    # Full sibling story lists for tree view
    all_siblings      = fc.get("sibling_stories") or []
    completed_stories = fc.get("completed_stories") or []
    in_progress_stories = fc.get("in_progress_stories") or []
    pending_stories   = fc.get("pending_stories") or []

    # Current story values. Prefer the full stored story, then sibling context,
    # then the generated story id so the tree never renders a blank row.
    current_from_context = _story_from_feature_context(jira_id, fc)
    own_summary = story_raw.get("summary") or current_from_context.get("summary") or jira_id
    own_status = story_raw.get("status") or current_from_context.get("status") or status_info[0]
    own_status_category = story_raw.get("status_category") or current_from_context.get("status_category") or ""
    own_assignee = story_raw.get("assignee") or current_from_context.get("assignee") or "—"

    # ── Real Jira status overrides DevFlow stage label for table & tree ────────
    # Use actual Jira status so table shows "Done" not "In Progress" for a
    # story that is Done in Jira but only reached stage=start in DevFlow.
    _jira_status_colors = {
        "done":         ("#1a4731", "#3fb950"),
        "in progress":  ("#1f3a6e", "#388bfd"),
        "in analysis":  ("#2a2200", "#d29922"),
        "pr created":   ("#1a4731", "#3fb950"),
        "ready":        ("#1a3a4a", "#58a6ff"),
        "draft":        ("#21262d", "#8b949e"),
        "to do":        ("#21262d", "#8b949e"),
    }
    _s_lower = (own_status or "").lower()
    _bg, _fg = next(
        (v for k, v in _jira_status_colors.items() if k in _s_lower),
        ("#21262d", "#8b949e")
    )
    # For MR created, always show green
    if stage == "create_mr" and mr_url:
        own_status = "PR Created"
        _bg, _fg = "#1a4731", "#3fb950"

    return {
        "id": jira_id,
        "summary": own_summary,
        "jira_status": own_status,
        "jira_status_category": own_status_category,
        "assignee": own_assignee,
        "feature_key": feature_key,
        "feature_name": feature_name,
        "feature_status": feature_status,
        "feature_desc": feature_desc,
        "stage": stage,
        "stage_timings": timings,
        "status_label": own_status,      # ← real Jira status (Done / In Progress / In Analysis)
        "status_bg": _bg,
        "status_color": _fg,
        "confidence": ca.get("confidence") or "—",
        "updated": _parse_date(updated),
        "ai_time": _fmt_duration(ai_s),
        "human_time": _fmt_duration(hu_s),
        "approvals": approvals,
        "files_changed": len(files_changed),
        "files_list": files_changed[:20],
        "test_verdict": "passed" if test_ok else ("failed" if test_ok is False else "—"),
        "mr_url": mr_url,
        "mr_title": mr_title,
        "next_gate": next_gate,
        "progress_pct": progress_pct,
        "completed_siblings": completed_siblings,
        "jira_url": _jira_url(jira_id),
        "raw_ai_s": ai_s,
        "subtasks": story_raw.get("subtasks") or [],
        "live_jira_status": live_status,
        "live_jira_error": live_error,
        # Tree data
        "completed_stories": completed_stories,
        "in_progress_stories": in_progress_stories,
        "pending_stories": pending_stories,
        "all_siblings": all_siblings,
    }


def load_all_stories() -> list[dict[str, Any]]:
    stories = []
    for path in sorted(STORIES_DIR.glob("*.json")):
        s = load_story(path)
        if s:
            stories.append(s)
    return sorted(stories, key=lambda x: x.get("updated") or "", reverse=True)


