def _story_detail_tree(s: dict[str, Any]) -> str:
    """Render expanded detail for a DevFlow-implemented story."""
    timings   = s.get("stage_timings") or []
    mr_url    = s.get("mr_url") or ""
    mr_title  = s.get("mr_title") or ""
    files     = s.get("files_list") or []
    test_v    = s.get("test_verdict") or "—"
    ai_time   = s.get("ai_time") or "—"
    hu_time   = s.get("human_time") or "—"
    next_gate = s.get("next_gate") or ""
    conf      = s.get("confidence") or "—"
    subtasks  = s.get("subtasks") or []

    # Stage timeline rows
    stage_rows = ""
    for i, t in enumerate(timings):
        stage_rows += _stage_row(t, is_last=(i == len(timings) - 1))

    if not stage_rows and s["stage"] != "start":
        stage_rows = _stage_row({"stage": s["stage"], "actor": "ai", "elapsed_s": 0}, is_last=True)
    elif not stage_rows:
        stage_rows = '<div class="tree-stage"><span class="tree-connector">└─</span><span class="stage-label">📥 Start — Analysis complete</span></div>'

    # MR link
    mr_html = ""
    if mr_url:
        mr_html = f'<div class="detail-item">🔗 <a href="{mr_url}" target="_blank" style="color:#58a6ff;">MR: {mr_title or mr_url}</a></div>'
    elif next_gate:
        mr_html = f'<div class="detail-item">⏸ Next: <span style="color:#d29922;">{next_gate}</span></div>'

    # Files
    files_html = ""
    if files:
        file_list = "".join(f'<span class="file-chip">{f.split("/")[-1]}</span>' for f in files[:6])
        if len(files) > 6:
            file_list += f'<span class="file-chip" style="color:#8b949e;">+{len(files)-6} more</span>'
        files_html = f'<div class="detail-item">📁 {file_list}</div>'

    test_color = "#3fb950" if test_v == "passed" else "#f85149" if test_v == "failed" else "#8b949e"
    subtask_html = _subtask_list_html(subtasks)

    return f'''
    <div class="story-detail-tree">
      <div class="detail-grid">
        <div class="detail-item">🤖 AI: <b style="color:#a371f7;">{ai_time}</b></div>
        <div class="detail-item">👤 Human: <b style="color:#f78166;">{hu_time}</b></div>
        <div class="detail-item">🧪 Tests: <b style="color:{test_color};">{test_v}</b></div>
        <div class="detail-item">🔍 Code: <b style="color:#79c0ff;">{conf}</b></div>
      </div>
      {files_html}
      {mr_html}
      {subtask_html}
      <div class="stage-timeline">{stage_rows}</div>
    </div>'''


