    dur     = _fmt_duration(elapsed)
    actor_icon = "🤖" if actor == "ai" else "👤"
    actor_color = "#58a6ff" if actor == "ai" else "#f78166"
    connector = "└─" if is_last else "├─"
    return f'''
    <div class="tree-stage">
      <span class="tree-connector">{connector}</span>
      <span class="stage-label">{label}</span>
      <span style="color:{actor_color};font-size:.75rem;margin-left:8px;">{actor_icon} {actor}</span>
      <span class="tree-meta" style="margin-left:8px;">{dur}</span>
    </div>'''


