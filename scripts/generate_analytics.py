def auto_project_info() -> dict[str, str]:
    """Detect project name, short badge, language, and stack from memory files.

    Detection order:
      1. Automation/.memory/project-profile.json   — generated by setup_project.py
      2. Automation/.memory/repo-config.json        — repo root path
      3. AGENTS.md / README.md                      — fallback name from heading
      4. repo folder name                           — last resort
    """
    info: dict[str, str] = {
        "name": "",          # Full project name  e.g. "cdp-linking-middleware"
        "short": "",         # Badge label        e.g. "CDP-LMW"
        "language": "",      # e.g. "java"
        "label": "",         # e.g. "Spring Boot (Maven)"
        "category": "",      # e.g. "backend"
        "repo_root": str(REPO_ROOT),
    }

    # ── 1. project-profile.json ───────────────────────────────────────────────
    profile_path = AUTO_DIR / ".memory" / "project-profile.json"
    if profile_path.exists():
        try:
            profile = json.loads(profile_path.read_text(encoding="utf-8"))
            info["language"] = profile.get("language") or ""
            info["label"]    = profile.get("label") or ""
            info["category"] = profile.get("category") or ""
            rr = profile.get("repo_root") or ""
            if rr:
                info["name"] = Path(rr).name
        except Exception:
            pass

    # ── 2. repo-config.json ───────────────────────────────────────────────────
    config_path = AUTO_DIR / ".memory" / "repo-config.json"
    if config_path.exists() and not info["name"]:
        try:
            cfg = json.loads(config_path.read_text(encoding="utf-8"))
            rr = cfg.get("repo_root") or ""
            if rr:
                info["name"] = Path(rr).name
        except Exception:
            pass

    # ── 3. Fallback to actual repo folder name ────────────────────────────────
    if not info["name"]:
        info["name"] = REPO_ROOT.name

    # ── Build short badge from name ───────────────────────────────────────────
    # "cdp-linking-middleware" → "CDP-LMW"
    # "my-backend-service"    → "MBS"
    # "frontend-app"          → "FE-APP"
    name = info["name"]
    parts = [p for p in name.replace("_", "-").split("-") if p]
    # Build short code: "cdp-linking-middleware" → "CDP-LMW"
    # Strategy: first part + initials of remaining parts
    if len(parts) >= 2:
        first = parts[0].upper()
        rest  = "".join(p[0].upper() for p in parts[1:])
        candidate = f"{first}-{rest}"
        info["short"] = candidate[:10]  # cap at 10 chars
    elif parts:
        info["short"] = parts[0][:6].upper()
    else:
        info["short"] = name[:6].upper()

    return info


